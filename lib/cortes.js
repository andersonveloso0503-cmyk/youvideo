const iguais = (a, b) => String(a || '').trim().toLowerCase() === String(b || '').trim().toLowerCase();

/**
 * Fábrica: a IA escolhe `qtd` cortes do tipo pedido ('filme' ou 'comico'), sem repetir os já usados.
 * Devolve [{ nome, cena }]. Se a IA falhar ou devolver menos, completa com as listas prontas daqui.
 */
export async function temasCortesDaIa(qtd, tipo, evitar = []) {
  const t = tipo === 'comico' ? 'comico' : 'filme';
  const usados = evitar.filter(Boolean).map(String);
  let lista = [];
  if (qtd > 0 && process.env.GROQ_API_KEY) {
    const pedir = async (modelo) => {
      const r = await fetch('https://api.groq.com/openai/v1/chat/completions', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json', Authorization: `Bearer ${process.env.GROQ_API_KEY}` },
        body: JSON.stringify({
          model: modelo,
          temperature: 0.9,
          response_format: { type: 'json_object' },
          messages: [
            { role: 'system', content: `${PEDIDO[t]} O canal é cristão e brasileiro, chamado "Em Nome de Jesus". Responda só JSON: {"cortes": [{"nome": "...", "cena": "..."}]}. Nada repetido nem parecido com a lista de já usados.` },
            { role: 'user', content: `Quero ${qtd} diferentes.\n\nJá usados (não repetir):\n${usados.slice(0, 250).map((x) => `- ${x}`).join('\n') || '(nenhum)'}` },
          ],
        }),
      });
      const d = await r.json();
      if (!r.ok) throw new Error(d?.error?.message || `Groq respondeu ${r.status}`);
      return JSON.parse(d.choices?.[0]?.message?.content || '{}').cortes || [];
    };
    try {
      try {
        lista = await pedir('openai/gpt-oss-120b');
      } catch {
        lista = await pedir('llama-3.3-70b-versatile');
      }
    } catch {
      lista = []; // IA fora do ar: segue com as listas prontas
    }
  }
  const saida = [];
  const entra = (nome, cena) => {
    const n = String(nome || '').trim().slice(0, 120);
    const c = String(cena || '').trim().slice(0, 900);
    if (!n || !c || saida.length >= qtd) return;
    if (usados.some((u) => iguais(u, n)) || saida.some((x) => iguais(x.nome, n))) return;
    saida.push({ nome: n, cena: c });
  };
  (Array.isArray(lista) ? lista : []).forEach((x) => entra(x?.nome, x?.cena));
  (t === 'comico' ? SITUACOES_COMICAS : CENAS_FILME).forEach((x) => entra(x.nome, x.tema));
  return saida;
}
